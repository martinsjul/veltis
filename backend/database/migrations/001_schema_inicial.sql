CREATE EXTENSION IF NOT EXISTS postgis;

-- ============================================================
-- 1. CRIACAO DAS TABELAS
-- ============================================================

CREATE TABLE IBGE_MUNICIPIOS (
    CD_MUN CHAR(7) NOT NULL,
    NM_MUN VARCHAR(100) NOT NULL,
    CD_RGI CHAR(6),
    NM_RGI VARCHAR(100),
    CD_RGINT CHAR(4),
    NM_RGINT VARCHAR(100),
    CD_UF CHAR(2),
    NM_UF VARCHAR(50),
    SIGLA_UF CHAR(2),
    CD_REGIAO CHAR(1),
    NM_REGIAO VARCHAR(30),
    SIGLA_RG CHAR(2),
    CD_CONCURB CHAR(7),
    NM_CONCURB VARCHAR(100),
    AREA_KM2 NUMERIC(12,3),
    GEOMETRY GEOMETRY(MULTIPOLYGON, 4674) NOT NULL
);

CREATE TABLE IBGE_DEMOGRAFICO (
    ID_DEMOGRAFICO BIGINT GENERATED ALWAYS AS IDENTITY NOT NULL,
    CD_MUN CHAR(7) NOT NULL,
    CO_PERIODO VARCHAR(20) NOT NULL,
    CD_AGREGADO VARCHAR(12) NOT NULL,
    CD_VARIAVEL VARCHAR(20) NOT NULL,
    NO_VARIAVEL VARCHAR(255),
    DS_UNIDADE VARCHAR(100),
    VL_INDICADOR NUMERIC(24,8),
    ID_INGESTAO BIGINT
);

CREATE TABLE IBGE_DEMO_CLASSIF (
    ID_DEMOGRAFICO BIGINT NOT NULL,
    CD_CLASSIFICACAO VARCHAR(20) NOT NULL,
    NO_CLASSIFICACAO VARCHAR(150),
    CD_CATEGORIA VARCHAR(30) NOT NULL,
    NO_CATEGORIA VARCHAR(200)
);

CREATE TABLE INEP_ESCOLA (
    NU_ANO_CENSO SMALLINT NOT NULL,
    CO_ENTIDADE INTEGER NOT NULL,
    NO_ENTIDADE VARCHAR(255) NOT NULL,
    CO_MUNICIPIO CHAR(7) NOT NULL,
    NO_MUNICIPIO VARCHAR(150) NOT NULL,
    SG_UF CHAR(2) NOT NULL,
    TP_DEPENDENCIA SMALLINT NOT NULL,
    TP_LOCALIZACAO SMALLINT NOT NULL,
    TP_SITUACAO_FUNCIONAMENTO SMALLINT NOT NULL,
    IN_COMUM_MEDIO_MEDIO BOOLEAN,
    IN_COMUM_MEDIO_INTEGRADO BOOLEAN,
    IN_COMUM_MEDIO_FIC BOOLEAN,
    IN_COMUM_MEDIO_NORMAL BOOLEAN,
    IN_ITINERARIO_TECN_PROF BOOLEAN
);

CREATE TABLE INEP_CURSO_TECNICO (
    NU_ANO_CENSO SMALLINT NOT NULL,
    CO_ENTIDADE INTEGER NOT NULL,
    CO_MUNICIPIO CHAR(7) NOT NULL,
    NO_MUNICIPIO VARCHAR(150) NOT NULL,
    CO_CURSO_EDUC_PROFISSIONAL INTEGER NOT NULL,
    NO_CURSO_EDUC_PROFISSIONAL VARCHAR(255) NOT NULL,
    ID_AREA_CURSO_PROFISSIONAL INTEGER,
    NO_AREA_CURSO_PROFISSIONAL VARCHAR(255),
    QT_CURSO_TEC INTEGER,
    QT_MAT_CURSO_TEC INTEGER
);

CREATE TABLE MEC_IES (
    NU_ANO_CENSO SMALLINT NOT NULL,
    CO_IES INTEGER NOT NULL,
    NO_IES VARCHAR(255) NOT NULL,
    SG_IES VARCHAR(50),
    CO_MUNICIPIO_IES CHAR(7) NOT NULL,
    NO_MUNICIPIO_IES VARCHAR(150) NOT NULL,
    SG_UF_IES CHAR(2) NOT NULL,
    TP_ORGANIZACAO_ACADEMICA SMALLINT NOT NULL,
    TP_REDE SMALLINT NOT NULL,
    TP_CATEGORIA_ADMINISTRATIVA SMALLINT NOT NULL,
    DS_ENDERECO_IES VARCHAR(255),
    NO_BAIRRO_IES VARCHAR(100),
    NU_CEP_IES CHAR(8)
);

CREATE TABLE MEC_CURSOS (
    ID_OFERTA_CURSO BIGINT GENERATED ALWAYS AS IDENTITY NOT NULL,
    NU_ANO_CENSO SMALLINT NOT NULL,
    TP_DIMENSAO SMALLINT NOT NULL,
    CO_IES INTEGER NOT NULL,
    CO_CURSO INTEGER NOT NULL,
    NO_CURSO VARCHAR(255) NOT NULL,
    CO_MUNICIPIO CHAR(7),
    NO_MUNICIPIO VARCHAR(150),
    SG_UF CHAR(2),
    NO_CINE_AREA_GERAL VARCHAR(120),
    NO_CINE_AREA_ESPECIFICA VARCHAR(120),
    TP_GRAU_ACADEMICO SMALLINT,
    IN_GRATUITO BOOLEAN NOT NULL,
    TP_MODALIDADE_ENSINO SMALLINT NOT NULL,
    TP_NIVEL_ACADEMICO SMALLINT NOT NULL,
    QT_CURSO INTEGER NOT NULL,
    QT_VG_TOTAL INTEGER NOT NULL,
    QT_MAT INTEGER NOT NULL
);

CREATE TABLE FONTE_DADOS (
    ID_FONTE BIGINT GENERATED ALWAYS AS IDENTITY NOT NULL,
    NO_ORGAO VARCHAR(150) NOT NULL,
    NO_FONTE VARCHAR(255) NOT NULL,
    DS_URL_OFICIAL TEXT,
    DS_PERIODICIDADE VARCHAR(80),
    DS_TIPO_FONTE VARCHAR(40) NOT NULL,
    DS_OBSERVACAO TEXT
);

CREATE TABLE CONTROLE_INGESTAO (
    ID_INGESTAO BIGINT GENERATED ALWAYS AS IDENTITY NOT NULL,
    ID_FONTE BIGINT NOT NULL,
    CO_PERIODO_REFERENCIA VARCHAR(20),
    DS_VERSAO VARCHAR(80),
    NO_ARQUIVO_ORIGEM VARCHAR(255) NOT NULL,
    DT_OBTENCAO DATE,
    DT_PROCESSAMENTO TIMESTAMP NOT NULL,
    DS_HASH_SHA256 CHAR(64),
    QT_REGISTROS_LIDOS BIGINT,
    QT_REGISTROS_CARREGADOS BIGINT,
    QT_REGISTROS_REJEITADOS BIGINT,
    DS_STATUS VARCHAR(30) NOT NULL,
    DS_OBSERVACAO TEXT
);

CREATE TABLE ESCOLA_LOCALIZACAO (
    ID_LOCALIZACAO BIGINT GENERATED ALWAYS AS IDENTITY NOT NULL,
    NU_ANO_CENSO SMALLINT NOT NULL,
    CO_ENTIDADE INTEGER NOT NULL,
    DS_ENDERECO VARCHAR(350),
    NU_CEP CHAR(8),
    NU_TELEFONE VARCHAR(30),
    VL_LATITUDE NUMERIC(10,7),
    VL_LONGITUDE NUMERIC(10,7),
    GEOMETRY GEOMETRY(POINT, 4674),
    ID_FONTE BIGINT NOT NULL,
    TP_METODO_LOCALIZACAO VARCHAR(40) NOT NULL,
    ID_INGESTAO BIGINT
);

-- ============================================================
-- 2. CHAVES PRIMARIAS
-- ============================================================

ALTER TABLE IBGE_MUNICIPIOS
ADD CONSTRAINT PK_IBGE_MUNICIPIOS
PRIMARY KEY (CD_MUN);

ALTER TABLE IBGE_DEMOGRAFICO
ADD CONSTRAINT PK_IBGE_DEMOGRAFICO
PRIMARY KEY (ID_DEMOGRAFICO);

ALTER TABLE IBGE_DEMO_CLASSIF
ADD CONSTRAINT PK_IBGE_DEMO_CLASSIF
PRIMARY KEY (ID_DEMOGRAFICO, CD_CLASSIFICACAO);

ALTER TABLE INEP_ESCOLA
ADD CONSTRAINT PK_INEP_ESCOLA
PRIMARY KEY (NU_ANO_CENSO, CO_ENTIDADE);

ALTER TABLE INEP_CURSO_TECNICO
ADD CONSTRAINT PK_INEP_CURSO_TECNICO
PRIMARY KEY (
    NU_ANO_CENSO,
    CO_ENTIDADE,
    CO_CURSO_EDUC_PROFISSIONAL
);

ALTER TABLE MEC_IES
ADD CONSTRAINT PK_MEC_IES
PRIMARY KEY (NU_ANO_CENSO, CO_IES);

ALTER TABLE MEC_CURSOS
ADD CONSTRAINT PK_MEC_CURSOS
PRIMARY KEY (ID_OFERTA_CURSO);

ALTER TABLE FONTE_DADOS
ADD CONSTRAINT PK_FONTE_DADOS
PRIMARY KEY (ID_FONTE);

ALTER TABLE CONTROLE_INGESTAO
ADD CONSTRAINT PK_CONTROLE_INGESTAO
PRIMARY KEY (ID_INGESTAO);

ALTER TABLE ESCOLA_LOCALIZACAO
ADD CONSTRAINT PK_ESCOLA_LOCALIZACAO
PRIMARY KEY (ID_LOCALIZACAO);

-- ============================================================
-- 3. CHAVES ESTRANGEIRAS
-- ============================================================

ALTER TABLE IBGE_DEMOGRAFICO
ADD CONSTRAINT FK_IBGE_DEMOGRAFICO_MUNICIPIO
FOREIGN KEY (CD_MUN)
REFERENCES IBGE_MUNICIPIOS (CD_MUN);

ALTER TABLE IBGE_DEMOGRAFICO
ADD CONSTRAINT FK_IBGE_DEMOGRAFICO_INGESTAO
FOREIGN KEY (ID_INGESTAO)
REFERENCES CONTROLE_INGESTAO (ID_INGESTAO);

ALTER TABLE IBGE_DEMO_CLASSIF
ADD CONSTRAINT FK_IBGE_DEMO_CLASSIF_DEMOGRAFICO
FOREIGN KEY (ID_DEMOGRAFICO)
REFERENCES IBGE_DEMOGRAFICO (ID_DEMOGRAFICO);

ALTER TABLE INEP_ESCOLA
ADD CONSTRAINT FK_INEP_ESCOLA_MUNICIPIO
FOREIGN KEY (CO_MUNICIPIO)
REFERENCES IBGE_MUNICIPIOS (CD_MUN);

ALTER TABLE INEP_CURSO_TECNICO
ADD CONSTRAINT FK_INEP_CURSO_TECNICO_ESCOLA
FOREIGN KEY (NU_ANO_CENSO, CO_ENTIDADE)
REFERENCES INEP_ESCOLA (NU_ANO_CENSO, CO_ENTIDADE);

ALTER TABLE INEP_CURSO_TECNICO
ADD CONSTRAINT FK_INEP_CURSO_TECNICO_MUNICIPIO
FOREIGN KEY (CO_MUNICIPIO)
REFERENCES IBGE_MUNICIPIOS (CD_MUN);

ALTER TABLE MEC_CURSOS
ADD CONSTRAINT FK_MEC_CURSOS_IES
FOREIGN KEY (NU_ANO_CENSO, CO_IES)
REFERENCES MEC_IES (NU_ANO_CENSO, CO_IES);

ALTER TABLE MEC_CURSOS
ADD CONSTRAINT FK_MEC_CURSOS_MUNICIPIO
FOREIGN KEY (CO_MUNICIPIO)
REFERENCES IBGE_MUNICIPIOS (CD_MUN);

ALTER TABLE CONTROLE_INGESTAO
ADD CONSTRAINT FK_CONTROLE_INGESTAO_FONTE
FOREIGN KEY (ID_FONTE)
REFERENCES FONTE_DADOS (ID_FONTE);

ALTER TABLE ESCOLA_LOCALIZACAO
ADD CONSTRAINT FK_ESCOLA_LOCALIZACAO_ESCOLA
FOREIGN KEY (NU_ANO_CENSO, CO_ENTIDADE)
REFERENCES INEP_ESCOLA (NU_ANO_CENSO, CO_ENTIDADE);

ALTER TABLE ESCOLA_LOCALIZACAO
ADD CONSTRAINT FK_ESCOLA_LOCALIZACAO_FONTE
FOREIGN KEY (ID_FONTE)
REFERENCES FONTE_DADOS (ID_FONTE);

ALTER TABLE ESCOLA_LOCALIZACAO
ADD CONSTRAINT FK_ESCOLA_LOCALIZACAO_INGESTAO
FOREIGN KEY (ID_INGESTAO)
REFERENCES CONTROLE_INGESTAO (ID_INGESTAO);

-- ============================================================
-- 4. RESTRICOES CHECK
-- ============================================================

ALTER TABLE IBGE_MUNICIPIOS
ADD CONSTRAINT CK_IBGE_MUNICIPIOS_AREA
CHECK (AREA_KM2 IS NULL OR AREA_KM2 >= 0);

ALTER TABLE INEP_ESCOLA
ADD CONSTRAINT CK_INEP_ESCOLA_DEPENDENCIA
CHECK (TP_DEPENDENCIA IN (1, 2, 3, 4));

ALTER TABLE INEP_ESCOLA
ADD CONSTRAINT CK_INEP_ESCOLA_LOCALIZACAO
CHECK (TP_LOCALIZACAO IN (1, 2));

ALTER TABLE INEP_ESCOLA
ADD CONSTRAINT CK_INEP_ESCOLA_SITUACAO
CHECK (TP_SITUACAO_FUNCIONAMENTO IN (1, 2, 3, 4));

ALTER TABLE INEP_CURSO_TECNICO
ADD CONSTRAINT CK_INEP_CURSO_TEC_QT_CURSO
CHECK (QT_CURSO_TEC IS NULL OR QT_CURSO_TEC >= 0);

ALTER TABLE INEP_CURSO_TECNICO
ADD CONSTRAINT CK_INEP_CURSO_TEC_QT_MAT
CHECK (QT_MAT_CURSO_TEC IS NULL OR QT_MAT_CURSO_TEC >= 0);

ALTER TABLE MEC_IES
ADD CONSTRAINT CK_MEC_IES_ORGANIZACAO
CHECK (TP_ORGANIZACAO_ACADEMICA IN (1, 2, 3, 4, 5));

ALTER TABLE MEC_IES
ADD CONSTRAINT CK_MEC_IES_REDE
CHECK (TP_REDE IN (1, 2));

ALTER TABLE MEC_CURSOS
ADD CONSTRAINT CK_MEC_CURSOS_MODALIDADE
CHECK (TP_MODALIDADE_ENSINO IN (1, 2));

ALTER TABLE MEC_CURSOS
ADD CONSTRAINT CK_MEC_CURSOS_NIVEL
CHECK (TP_NIVEL_ACADEMICO IN (1, 2));

ALTER TABLE MEC_CURSOS
ADD CONSTRAINT CK_MEC_CURSOS_QT_CURSO
CHECK (QT_CURSO >= 0);

ALTER TABLE MEC_CURSOS
ADD CONSTRAINT CK_MEC_CURSOS_QT_VAGAS
CHECK (QT_VG_TOTAL >= 0);

ALTER TABLE MEC_CURSOS
ADD CONSTRAINT CK_MEC_CURSOS_QT_MATRICULAS
CHECK (QT_MAT >= 0);

ALTER TABLE FONTE_DADOS
ADD CONSTRAINT CK_FONTE_DADOS_TIPO
CHECK (
    DS_TIPO_FONTE IN (
        'OFICIAL_PRINCIPAL',
        'OFICIAL_COMPLEMENTAR',
        'INTERNA'
    )
);

ALTER TABLE CONTROLE_INGESTAO
ADD CONSTRAINT CK_CONTROLE_INGESTAO_LIDOS
CHECK (QT_REGISTROS_LIDOS IS NULL OR QT_REGISTROS_LIDOS >= 0);

ALTER TABLE CONTROLE_INGESTAO
ADD CONSTRAINT CK_CONTROLE_INGESTAO_CARREGADOS
CHECK (QT_REGISTROS_CARREGADOS IS NULL OR QT_REGISTROS_CARREGADOS >= 0);

ALTER TABLE CONTROLE_INGESTAO
ADD CONSTRAINT CK_CONTROLE_INGESTAO_REJEITADOS
CHECK (QT_REGISTROS_REJEITADOS IS NULL OR QT_REGISTROS_REJEITADOS >= 0);

ALTER TABLE CONTROLE_INGESTAO
ADD CONSTRAINT CK_CONTROLE_INGESTAO_STATUS
CHECK (
    DS_STATUS IN (
        'INICIADA',
        'CONCLUIDA',
        'FALHA',
        'PARCIAL'
    )
);

ALTER TABLE ESCOLA_LOCALIZACAO
ADD CONSTRAINT CK_ESCOLA_LOCALIZACAO_LATITUDE
CHECK (
    VL_LATITUDE IS NULL
    OR VL_LATITUDE BETWEEN -90 AND 90
);

ALTER TABLE ESCOLA_LOCALIZACAO
ADD CONSTRAINT CK_ESCOLA_LOCALIZACAO_LONGITUDE
CHECK (
    VL_LONGITUDE IS NULL
    OR VL_LONGITUDE BETWEEN -180 AND 180
);

ALTER TABLE ESCOLA_LOCALIZACAO
ADD CONSTRAINT CK_ESCOLA_LOCALIZACAO_METODO
CHECK (
    TP_METODO_LOCALIZACAO IN (
        'COORDENADA_OFICIAL',
        'ENDERECO_OFICIAL',
        'GEOCODIFICADO'
    )
);

-- ============================================================
-- 5. RESTRICOES UNIQUE
-- ============================================================

ALTER TABLE ESCOLA_LOCALIZACAO
ADD CONSTRAINT UQ_ESCOLA_LOCALIZACAO_FONTE
UNIQUE (NU_ANO_CENSO, CO_ENTIDADE, ID_FONTE);

-- IMPORTANTE:
-- IBGE_DEMOGRAFICO NAO recebe UNIQUE apenas em
-- (CD_MUN, CO_PERIODO, CD_AGREGADO, CD_VARIAVEL),
-- pois classificacoes e categorias tambem fazem parte
-- da identidade logica do resultado SIDRA.

-- ============================================================
-- 6. INDICES ESPACIAIS
-- ============================================================

CREATE INDEX IDX_IBGE_MUNICIPIOS_GEOMETRY
ON IBGE_MUNICIPIOS
USING GIST (GEOMETRY);

CREATE INDEX IDX_ESCOLA_LOCALIZACAO_GEOMETRY
ON ESCOLA_LOCALIZACAO
USING GIST (GEOMETRY);

